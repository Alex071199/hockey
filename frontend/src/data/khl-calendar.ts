export function getKhlDates(): string[] {
  const dates = [...new Set(khlCalendar.map((m) => m.date))];
  return dates.sort();
}

export function getKhlMatchesByDate(date: string): KhlMatch[] {
  return khlCalendar.filter((m) => m.date === date).sort((a, b) => a.time.localeCompare(b.time));
}

export function formatKhlDate(dateStr: string): string {
  const d = new Date(dateStr + "T00:00:00");
  const days = ["Вс", "Пн", "Вт", "Ср", "Чт", "Пт", "Сб"];
  const months = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];
  return `${days[d.getDay()]}, ${d.getDate()} ${months[d.getMonth()]}`;
}
